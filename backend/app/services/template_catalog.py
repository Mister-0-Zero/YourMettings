DEFAULT_TEMPLATE_ID = UUID("019a0120-0000-7000-8000-000000000001")
_SECTION_NAMESPACE = UUID("83e258fb-b803-4c75-9458-a10114cb2d5a")


def _sections(key, rows):
    result = []
    for position, row in enumerate(rows):
        title, instruction, *children = row
        result.append({"id": str(uuid5(_SECTION_NAMESPACE, f"{key}/{position}")),
            "title": title, "instruction": instruction, "position": position,
            "required": True, "type": "repeated" if children else "section",
            "children": _sections(f"{key}/{position}", children[0]) if children else []})
    return result


def _template(number, name, description, instructions, rows, mode="strict"):
    identifier = UUID(f"019a0120-0000-7000-8000-{number:012d}")
    definition = TemplateInput(name=name, description=description, structure_mode=mode,
        general_instructions=instructions, sections=_sections(str(identifier), rows)).model_dump(mode="json")
    return {"id": str(identifier), "owner_user_id": None, "is_system": True,
        "is_default": number == 1, **definition}


