def seed_system_templates(db: Session):
    """Insert missing stable built-ins without replacing existing definitions."""
    for definition in SYSTEM_TEMPLATES:
        data = dict(definition, id=UUID(definition["id"]))
        db.execute(insert(SummaryTemplate).values(**data).on_conflict_do_nothing())


def accessible_template(db: Session, id: UUID, *, lock=False):
    query = select(SummaryTemplate).where(SummaryTemplate.id == id, or_(
        SummaryTemplate.is_system.is_(True), SummaryTemplate.owner_user_id == current_user_id(db)))
    if lock:
        query = query.with_for_update()
    item = db.scalar(query)
    if item is None:
        fail(404, "not_found", "Шаблон не найден.")
    return item


def owned_template(db: Session, id: UUID, *, lock=False):
    item = accessible_template(db, id, lock=lock)
    if item.is_system:
        fail(403, "template_read_only", "Системный шаблон доступен только для чтения. Создайте копию.")
    return item


def resolve_template_snapshot(db: Session, template_id: UUID | None = None):
    """Lock until caller's transaction completes and detach a complete JSON snapshot."""
    item = accessible_template(db, template_id or DEFAULT_TEMPLATE_ID, lock=True)
    return TemplateOut.model_validate(item).model_dump(mode="json")
